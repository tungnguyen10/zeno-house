import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const fixtureUrl = new URL('../tests/__fixtures__/tenant-identity-normalization.json', import.meta.url)
const outputUrl = new URL('../supabase/verification/tenant_identity_normalization.sql', import.meta.url)
const fixture = JSON.parse(readFileSync(fixtureUrl, 'utf8'))
const cases = [
  ...fixture.phone.map(({ input, expected }) => ({
    kind: 'phone',
    input,
    // SQL deliberately retains compact invalid legacy phones instead of returning null.
    expected: expected ?? input.replace(/[\s.()-]/g, ''),
  })),
  ...fixture.idNumber.map(({ input, expected }) => ({ kind: 'id_number', input, expected })),
]
// Keep this artifact ASCII: JSON escapes are decoded by PostgreSQL, avoiding invisible SQL characters.
const encoded = JSON.stringify(cases, null, 2).replace(/[^\x20-\x7e\n]/g, char =>
  `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`)
const sql = `-- Generated by node scripts/generate-tenant-identity-sql-fixture.mjs; do not edit.
-- Source: tests/__fixtures__/tenant-identity-normalization.json
-- Run after the identity migration. Read-only assertions; raises on any mismatch.
-- Invalid phones intentionally retain their compact legacy form in SQL.
do $verify$
declare
  v_case jsonb;
  v_actual text;
  v_case_number integer := 0;
begin
  for v_case in select value from pg_catalog.jsonb_array_elements($fixture$${encoded}$fixture$::jsonb)
  loop
    v_case_number := v_case_number + 1;
    v_actual := case v_case ->> 'kind'
      when 'phone' then public.normalize_tenant_phone(v_case ->> 'input')
      else public.normalize_tenant_id_number(v_case ->> 'input')
    end;
    if v_actual is distinct from (v_case ->> 'expected') then
      raise exception 'TENANT_IDENTITY_NORMALIZATION_MISMATCH kind=% case=%', v_case ->> 'kind', v_case_number;
    end if;
  end loop;
end;
$verify$;
select true as shared_identity_normalization_fixture_passed;
`

if (process.argv.includes('--check')) {
  if (readFileSync(outputUrl, 'utf8') !== sql) {
    throw new Error('Tenant identity SQL fixture is stale; run node scripts/generate-tenant-identity-sql-fixture.mjs')
  }
}
else {
  writeFileSync(outputUrl, sql)
  process.stdout.write(`Generated ${fileURLToPath(outputUrl)} (${cases.length} cases)\n`)
}
